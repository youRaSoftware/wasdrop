/// Все «ручки» физики стакана в одном месте.
///
/// Единицы — мировые: стакан `AppDimens.worldWidth` = 360 в ширину,
/// скорости в ед/с, ускорения в ед/с². Подбирать «на ощупь» здесь:
/// слишком прыгает — [fruitRestitution] вниз; катаются по дну —
/// [fruitRollingResistance] вверх; «ватно», нет веса — [gravity] вверх
/// (тогда пересмотреть [maxSpeed]: он ограничивает скорость падения).
abstract final class PhysicsTuning {
  /// Сколько мировых единиц в метре Box2D. На картинку не влияет — только
  /// на допуски движка: спекулятивная дистанция контакта 0.02 м
  /// ([speculativeDistance]), люфт покоя 0.005 м = 0.6 ед. Стакан ≈ 3 м,
  /// вишня r = 0.125 м, арбуз r = 1.08 м — в рекомендованных Box2D
  /// 0.1–10 м. Box2D фиксирует масштаб при создании первого мира —
  /// другого источника этого числа быть не должно.
  static const double unitsPerMeter = 120;

  /// Дистанция, с которой Box2D заводит контакт ещё до касания
  /// (`Tolerances.speculativeDistance` = 4 × люфт). Падающий шар не должен
  /// проходить за один шаг больше неё, иначе контакт с дном возникнет уже
  /// внутри дна и шар «провалится» — отсюда число шагов на кадр.
  static const double speculativeDistance = 0.02 * unitsPerMeter;

  /// Бросок с верха стакана до дна ≈ 1–1.2 с (при 1500 казалось слишком
  /// быстро, при 400 — «ватно»).
  static const double gravity = 1000;

  /// Потолок скорости любого тела. Набирается за 0.8 с / 320 ед. падения,
  /// дальше фрукт летит с постоянной скоростью; вместе с
  /// [speculativeDistance] задаёт число шагов физики на кадр.
  static const double maxSpeed = 800;

  /// Верхняя граница числа шагов Box2D за кадр (при 60 fps нужно 6).
  static const int maxStepsPerFrame = 24;

  /// Подшагов солвера в каждом шаге.
  static const int subSteps = 2;

  /// Кадры длиннее этого (лаг, возврат из фона) не «догоняем»,
  /// а замедляем — иначе тела проскакивают друг сквозь друга.
  static const double maxFrameDt = 1 / 30;

  /// Жёсткость контактов (Box2D режет до ⅛ частоты подшагов).
  static const double contactHertz = 120;
  static const double contactDampingRatio = 10;

  // forge2d передаёт скорости WorldDef/BodyDef в Box2D без пересчёта
  // из метров, поэтому «метровые» дефолты Box2D умножены на масштаб.

  /// Скорость расталкивания пересёкшихся тел (3 м/с).
  static const double maxContactPushSpeed = 3 * unitsPerMeter;

  /// Ниже этой относительной скорости удар не отскакивает (1 м/с).
  static const double restitutionThreshold = 1 * unitsPerMeter;
  static const double hitEventThreshold = 1 * unitsPerMeter;

  /// Ниже этой скорости тело засыпает через 0.5 с (0.05 м/с).
  static const double sleepThreshold = 0.05 * unitsPerMeter;

  // --- Фрукт ------------------------------------------------------------

  static const double fruitDensity = 1;

  /// Со стенкой смешивается как √(a·b) → 0.45.
  static const double fruitFriction = 0.5;

  /// Отскок: 0.12 — «живой» удар без резины (при 0.22 любой тир
  /// подпрыгивал бы на ~20 ед. независимо от массы).
  static const double fruitRestitution = 0.12;

  /// Сопротивление качению, безразмерно (от масштаба не зависит).
  /// Box2D умножает лимит момента на радиус *большего* из двух тел:
  /// для вишни (r 15) на арбузе (r 130) эффективное значение в 8.7 раза
  /// выше, чем на полу, — при 0.1 мелкий фрукт на плече крупного был
  /// «приклеен» и не скатывался. Поэтому здесь малое значение, а
  /// торможение качения по дну даёт [angularDamping].
  static const double fruitRollingResistance = 0.02;

  /// Гасит вращение (и вместе с ним качение по дну): со 100 ед/с фрукт
  /// останавливается за ~2 с и ~70 ед. пути. Скатыванию по склону не
  /// мешает (предельная скорость ≈ ускорение / значение).
  static const double angularDamping = 0.6;
  static const double linearDamping = 0.02;
  static const double wallFriction = 0.4;

  // --- Слияние ----------------------------------------------------------

  /// Потолок скорости, унаследованной новым шаром от родителей.
  static const double mergeMaxSpeed = 600;

  // Слияние происходит по контакту Box2D, то есть при зазоре между кругами
  // не больше [speculativeDistance] (2.4 ед.). Более строгий порог по
  // реальному касанию пробовали: пары, улёгшиеся вплотную с зазором
  // 1–2 ед., тогда не сливались вовсе.

  // --- Реакции ----------------------------------------------------------

  /// Скорость удара (ед/с), с которой фрукт «ойкает».
  static const double squishSpeed = 110;

  /// Ниже этой скорости шар считается покоящимся (выше порога сна).
  static const double settledSpeed = 8;

  // --- Бонусы -----------------------------------------------------------

  /// Встряска: прирост скорости вверх у дна (подскок ≈ v²/2g ≈ 160 ед.,
  /// четверть стакана; при 380 куча лишь вздрагивала); у линии проигрыша —
  /// в [shakeTopFactor] раз меньше, верхним фруктам некуда лететь. Каждый
  /// фрукт получает свою долю от [shakeLiftJitter] до 1, чтобы куча
  /// рассыпалась, а не подпрыгивала строем. Боковой прирост — случайный в
  /// пределах ±[shakeSideSpeed].
  static const double shakeLiftSpeed = 560;
  static const double shakeLiftJitter = 0.6;
  static const double shakeSideSpeed = 240;
  static const double shakeTopFactor = 0.45;

  /// Случайный прирост угловой скорости при встряске, рад/с.
  static const double shakeSpin = 10;

  /// Пауза между встрясками, с.
  static const double shakeCooldown = 1.5;

  /// Дрожание стакана после встряски: амплитуда (ед.) и длительность (с).
  static const double shakeCameraAmplitude = 9;
  static const double shakeCameraDuration = 0.4;

  /// Бомбочка: фитиль до взрыва (с), радиус толчка соседей (в радиусах
  /// взорванного фрукта) и прирост скорости у самого центра.
  static const double bombFuse = 0.3;
  static const double bombPushRadius = 2.5;
  static const double bombPushSpeed = 260;

  /// «Продолжить» после проигрыша: убираются фрукты с центром выше
  /// `deadlineY + continueClearDepth` (верхняя треть стакана) и любой, чей
  /// верх выше линии, — чтобы после продолжения было куда бросать.
  static const double continueClearDepth = 180;
}
